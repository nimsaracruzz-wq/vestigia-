import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import Database from 'better-sqlite3';
import { PrismaClient } from '@prisma/client';
import { PrismaBetterSqlite3 } from '@prisma/adapter-better-sqlite3';
import express from 'express';
import { installSiteTraffic } from '../utils/siteTraffic.js';
import { safeErrorHandler } from '../utils/requestSafety.js';
import { trafficPath } from '../../shared/siteTraffic.js';

test('traffic uses persisted, deduplicated events, consent, safe paths, real presence expiry, and admin auth', async () => {
  const folder = await fs.mkdtemp(path.join(os.tmpdir(), 'vestigia-traffic-'));
  const file = path.join(folder, 'traffic.db'), sqlite = new Database(file);
  const migrations = path.resolve('backend/prisma/migrations');
  for (const name of (await fs.readdir(migrations)).sort()) if (name !== 'migration_lock.toml') sqlite.exec(await fs.readFile(path.join(migrations, name, 'migration.sql'), 'utf8'));
  sqlite.close();
  const db = new PrismaClient({ adapter: new PrismaBetterSqlite3({ url: 'file:' + file.replaceAll('\\', '/') }) });
  const app = express(); app.use(express.json());
  installSiteTraffic(app, db, (req, res, next) => { if (req.get('authorization') !== 'Bearer admin') { res.sendStatus(401); return; } next(); });
  app.use(safeErrorHandler);
  const server = app.listen(0, '127.0.0.1'); await new Promise<void>(resolve => server.once('listening', resolve));
  const base = 'http://127.0.0.1:' + (server.address() as { port: number }).port;
  const event = { consent: true, type: 'pageview', eventId: randomUUID(), visitorId: randomUUID(), sessionId: randomUUID(), path: '/shop?email=secret@example.invalid', device: 'mobile', referrer: 'https://www.google.com/search?q=private' };
  const post = (body: object, headers: Record<string, string> = {}) => fetch(base + '/api/traffic/event', { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: base, ...headers }, body: JSON.stringify(body) });
  const get = async (url: string) => (await fetch(base + '/api/admin/traffic/' + url, { headers: { Authorization: 'Bearer admin' } })).json();
  try {
    assert.equal((await fetch(base + '/api/admin/traffic/live')).status, 401);
    assert.equal((await post(event, { Origin: 'https://evil.invalid' })).status, 403);
    for (const [body, headers] of [[{ ...event, consent: false }, {}], [event, { DNT: '1' }], [event, { 'Sec-GPC': '1' }], [event, { 'User-Agent': 'Googlebot' }]] as [object, Record<string, string>][]) assert.equal((await post(body, headers)).status, 204);
    assert.equal(await db.trafficPageView.count(), 0);
    assert.equal((await post({ ...event, path: '/account' })).status, 400);
    const expired = new Date(Date.now() - 95 * 86400000);
    await db.trafficPageView.create({ data: { id: randomUUID(), sessionId: randomUUID(), visitorId: randomUUID(), path: '/', device: 'desktop', referrer: '', createdAt: expired } });
    await db.trafficSession.create({ data: { id: randomUUID(), visitorId: randomUUID(), path: '/', device: 'desktop', referrer: '', startedAt: expired, lastSeen: expired } });
    assert.equal((await post({ ...event, type: 'heartbeat' })).status, 204);
    assert.equal(await db.trafficSession.count(), 0);
    assert.equal(await db.trafficPageView.count(), 0);
    assert.equal((await post(event)).status, 204);
    assert.equal((await post(event)).status, 204);
    assert.equal(await db.trafficPageView.count(), 1);
    assert.equal((await post({ ...event, eventId: randomUUID(), visitorId: randomUUID() })).status, 409);
    assert.equal(await db.trafficPageView.count(), 1);
    const stored = await db.trafficPageView.findFirstOrThrow();
    assert.equal(stored.path, '/shop'); assert.equal(stored.referrer, 'www.google.com');
    assert.doesNotMatch(JSON.stringify(stored), /secret@|private|search\?/);
    const first = await get('summary?days=7');
    assert.equal(first.views, 1); assert.equal(first.visitors, 1); assert.equal(first.sessions, 1);
    assert.equal(first.daily.reduce((sum: number, row: { views: number }) => sum + row.views, 0), 1);
    assert.equal((await get('live')).activeSessions, 1);
    await db.trafficSession.update({ where: { id: event.sessionId }, data: { lastSeen: new Date(Date.now() - 91000) } });
    assert.equal((await get('live')).activeSessions, 0);
    await post({ ...event, type: 'heartbeat' });
    assert.equal((await get('live')).activeSessions, 1);
    assert.equal(await db.trafficPageView.count(), 1);
    await post({ ...event, eventId: randomUUID(), path: '/product/tee' });
    const second = await get('summary?days=7'); assert.equal(second.views, 2); assert.equal(second.visitors, 1); assert.equal(second.sessions, 1);
    assert.equal((await fetch(base + '/api/admin/traffic/summary?days=999', { headers: { Authorization: 'Bearer admin' } })).status, 400);
    assert.equal(trafficPath('/reset-password?token=private'), null);
    assert.equal(trafficPath('/admin/users'), null);
  } finally { await new Promise<void>(resolve => server.close(() => resolve())); await db.$disconnect(); }
});
